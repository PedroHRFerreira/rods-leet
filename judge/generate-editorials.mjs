// Regenerate canonical TypeScript editorials from reviewed private references.
// This script reads repository-owned code only; it never evaluates student source.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const directory = path.dirname(fileURLToPath(import.meta.url));
const source = fs.readFileSync(
  path.join(directory, "references/algorithms.ts"),
  "utf8",
);
const ast = ts.createSourceFile(
  "algorithms.ts",
  source,
  ts.ScriptTarget.Latest,
  true,
);
let entries;
for (const statement of ast.statements) {
  if (!ts.isVariableStatement(statement)) continue;
  for (const declaration of statement.declarationList.declarations) {
    if (declaration.name.getText(ast) === "referenceSolutions")
      entries = declaration.initializer;
  }
}
if (!entries || !ts.isObjectLiteralExpression(entries))
  throw new Error("Reference registry missing");
const sources = {};
for (const property of entries.properties) {
  if (!ts.isPropertyAssignment(property)) continue;
  const id = ts.isStringLiteral(property.name)
    ? property.name.text
    : property.name.getText(ast);
  if (id === "find-max" || id === "shortest-path") continue;
  const expression = property.initializer.getText(ast);
  const imports = expression.includes("MinHeap")
    ? 'import { MinHeap } from "./min-heap";\n\n'
    : "";
  sources[id] = `${imports}export const solve = ${expression};\n`;
}
const heap = fs.readFileSync(
  path.join(directory, "references/min-heap.ts"),
  "utf8",
);
const graph = fs.readFileSync(
  path.join(directory, "references/shortest-path.ts"),
  "utf8",
);
const graphAst = ts.createSourceFile(
  "shortest-path.ts",
  graph,
  ts.ScriptTarget.Latest,
  true,
);
const functionNode = graphAst.statements.find(
  (node) =>
    ts.isFunctionDeclaration(node) && node.name?.text === "shortestPath",
);
if (!functionNode) throw new Error("Graph reference missing");
const shortestPath =
  'import { MinHeap } from "./min-heap";\n\nexport type Graph = ReadonlyArray<ReadonlyArray<{ to: number; weight: number }>>;\n\n' +
  functionNode.getText(graphAst) +
  "\n";
fs.writeFileSync(
  path.join(directory, "editorial-sources.ts"),
  "// Generated by judge/generate-editorials.mjs. Private, never import from src/.\nexport const canonicalSources: Record<string, string> = " +
    JSON.stringify(sources, null, 2) +
    ";\nexport const heapSource = " +
    JSON.stringify(heap) +
    ";\nexport const shortestPathSource = " +
    JSON.stringify(shortestPath) +
    ";\n",
);
console.log(
  `Generated ${Object.keys(sources).length} canonical editorials and the graph project.`,
);
